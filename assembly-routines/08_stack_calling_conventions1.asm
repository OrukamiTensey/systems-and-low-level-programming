section .data
    array1 dw 1, 3, 5, 7, 9            ; Перший масив слів (2 байти кожен)
    array2 dw 2, 4, 6, 8, 10           ; Другий масив слів
    size1 equ 5                        ; Розмір першого масиву
    size2 equ 5                        ; Розмір другого масиву
    combined resw size1 + size2        ; Результуючий масив (10 слів)

section .bss
    stack resb 256                     ; Резервуємо місце для стека 

section .text
global main                      ; Точка входу програми
main:
    mov ebp, esp                    ; Для коректного дебагу

    ; Ініціалізація сегментів
    mov ax, 0x10                     ; Завантажуємо сегмент даних
    mov ds, ax                       ; Встановлюємо сегмент даних
    mov ss, ax                       ; Встановлюємо сегмент стеку
    lea sp, [stack + 256]            ; Ініціалізуємо стек

    ; Підготовка даних
    lea si, [array1]                 ; Адреса першого масиву
    lea di, [array2]                 ; Адреса другого масиву
    lea bx, [combined]               ; Адреса нового масиву

    ; Пушимо параметри в стек для виклику процедури
    push si                          ; Передаємо адресу array1 через стек
    push di                          ; Передаємо адресу array2 через стек
    push size1                       ; Передаємо розмір першого масиву
    push bx                          ; Передаємо адресу нового масиву

    ; Викликаємо процедуру для об'єднання масивів
    call combine_arrays

    ; Завершення програми
    xor eax, eax                     ; Очищаємо регістр EAX
    mov ax, 0x4C00                   ; Завершення програми
    int 0x21                         ; Виклик переривання для завершення

; ---------------------------
; Процедура combine_arrays
; ---------------------------
combine_arrays:
    push bp                          ; Зберігаємо старе значення BP
    mov bp, sp                       ; Встановлюємо базовий вказівник

    ; Завантажуємо параметри зі стеку
    mov si, [bp + 6]                 ; Адреса першого масиву
    mov di, [bp + 4]                 ; Адреса другого масиву
    mov cx, [bp + 8]                 ; Розмір першого масиву (size1)
    mov bx, [bp + 10]                ; Адреса нового масиву (combined)

    xor dx, dx                        ; Лічильник для нового масиву (index = 0)

.loop:
    ; Копіюємо елементи з array1 на парні індекси нового масиву
    mov ax, [si]                     ; Завантажуємо елемент з array1
    mov [bx + dx], ax                ; Записуємо його в парний індекс нового масиву
    add si, 2                        ; Переходимо до наступного елемента array1
    add dx, 4                        ; Зсуваємося на 2 слова вперед в новому масиві

    ; Копіюємо елементи з array2 на непарні індекси нового масиву
    mov ax, [di]                     ; Завантажуємо елемент з array2
    mov [bx + dx - 2], ax            ; Записуємо його в непарний індекс нового масиву
    add di, 2                        ; Переходимо до наступного елемента array2

    loop .loop                       ; Повторюємо для всіх елементів array1

    pop bp                           ; Відновлюємо базовий вказівник
    ret                               ; Повертаємось з процедури